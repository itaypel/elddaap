/**
 * Generates supabase/migrations/*_seed.sql from supabase/seed-data.ts.
 * Run: node scripts/gen-seed.ts
 * IDs are derived from stable keys, so re-running produces the same SQL.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { operators, seedBookings } from "../supabase/seed-data.ts";
import { categories } from "../src/lib/data.ts";

const uuid = (key: string) => {
  const h = createHash("md5").update(key).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (xs: string[], type = "text") => (xs.length ? `array[${xs.map(q).join(", ")}]::${type}[]` : `'{}'::${type}[]`);
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const opId = (slug: string) => uuid(`operator:${slug}`);
const pkgId = (slug: string, key: string) => uuid(`package:${slug}:${key}`);

const blocked: Record<string, string[]> = { "water-battle": ["2026-12-06", "2026-12-07", "2026-12-31"] };
const out: string[] = ["-- Demo catalog and bookings. Generated by scripts/gen-seed.ts; do not edit by hand.", ""];

out.push("insert into public.categories (id, name, description, active, sort) values");
out.push(categories.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.desc)}, true, ${i})`).join(",\n") + ";", "");

for (const o of operators) {
  out.push(
    `insert into public.operators (id, slug, name, category_id, categories, tagline, about, rating, reviews_count, age_min, age_max, regions, region_label, duration_label, includes, locations, sponsored, verified, insured, response_hours, extras, facts, prepare, sub_ratings, cancellation, slots, plan, status, insurance_until, bookings_count, blocked_dates) values (` +
      [
        q(opId(o.slug)), q(o.slug), q(o.name), q(o.category), arr([o.category]), q(o.tagline), q(o.about), o.rating, o.reviewsCount,
        o.ageMin, o.ageMax, arr(o.regions), q(o.regionLabel), q(o.durationLabel), q(o.includes), arr(o.locations, "public.location_type"),
        !!o.sponsored, o.verified, o.insured, o.responseHours, json(o.extras), json(o.facts), arr(o.prepare), json(o.sub),
        q(o.cancellation), arr(o.slots), q(o.plan), q(o.status), q(o.insuranceUntil), o.bookingsCount, arr(blocked[o.slug] ?? [], "date"),
      ].join(", ") +
      ");",
  );
  out.push(
    `insert into public.operator_private (operator_id, business, documents) values (${q(opId(o.slug))}, ${json({ type: "עוסק מורשה" })}, ${json([
      { id: "insurance", name: "ביטוח צד ג׳", state: o.insuranceUntil === "10/2026" || o.insuranceUntil === "—" ? "expired" : "ok", note: o.insuranceUntil === "—" ? "" : `בתוקף עד ${o.insuranceUntil}` },
      { id: "noOffense", name: "אישור היעדר עבירות מין", state: "ok", note: "" },
      ...(o.category === "animals" ? [{ id: "license", name: "רישיון להצגת בעלי חיים", state: "missing", note: "נדרש בקטגוריה הזו" }] : []),
      { id: "business", name: "תעודת עוסק", state: "ok", note: "" },
    ])});`,
  );
  o.packages.forEach((p: any, i: number) => {
    out.push(
      `insert into public.packages (id, operator_id, name, duration_min, max_kids, age_min, age_max, price, includes, popular, active, extra_kid_price, sort) values (` +
        [q(pkgId(o.slug, p.id)), q(opId(o.slug)), q(p.name), p.durationMin, p.maxKids ?? "null", p.ageMin, p.ageMax, p.price, q(p.includes), !!p.popular, p.active, p.extraKidPrice ?? "null", i].join(", ") +
        ");",
    );
  });
  for (const r of o.reviews) {
    out.push(
      `insert into public.reviews (id, operator_id, author, context, when_label, score, text, reply, verified) values (` +
        [q(uuid(`review:${o.slug}:${r.id}`)), q(opId(o.slug)), q(r.author), q(r.context), q(r.when), r.score, q(r.text), q(r.reply ?? null), r.verified].join(", ") +
        ");",
    );
  }
  out.push("");
}

for (const b of seedBookings) {
  const op = operators.find((o) => o.slug === b.operatorSlug);
  const extrasCost = b.extras.reduce((s: number, id: string) => s + (op.extras.find((e: any) => e.id === id)?.price ?? 0), 0);
  out.push(
    `insert into public.bookings (id, operator_id, package_id, customer_name, customer_kind, phone, email, event_type, date, time, city, address, distance_km, kids, age_range, location_type, notes, extras, price, travel_fee, total, status, paid, rated, created_at) values (` +
      [
        b.id, q(opId(b.operatorSlug)), q(pkgId(b.operatorSlug, b.packageId)), q(b.customerName), q(b.customerKind), q(b.phone), q(b.email),
        q(b.eventType), q(b.date), q(b.time), q(b.city), q(b.address), b.distanceKm, b.kids, q(b.ageRange), q(b.locationType), q(b.notes),
        arr(b.extras), b.price, b.travelFee, b.price + b.travelFee + extrasCost, q(b.status), b.paid, b.rated, q(`${b.createdAt}+02`),
      ].join(", ") +
      ");",
  );
}

writeFileSync(new URL("../supabase/migrations/20261108120100_seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed: ${categories.length} categories, ${operators.length} operators, ${seedBookings.length} bookings`);
